/* LivedIn - builds PDF document specs for patient reports (pure; consumed by pdf.js). */
(function (root, factory) {
  const isNode = typeof module === 'object' && module.exports;
  const U = isNode ? require('./util.js') : root.LI;
  const A = isNode ? require('./analysis.js') : root.LI;
  const api = factory(U, A);
  if (isNode) module.exports = api; else { root.LI = root.LI || {}; Object.assign(root.LI, api); }
})(typeof self !== 'undefined' ? self : this, function (U, A) {
  'use strict';
  const B = (t) => ({ text: t, bold: true });

  /** opts.role decides how much is included: family only receives doctor notes marked "shared". */
  function patientReport(p, opts, now) {
    const role = (opts && opts.role) || 'family', secs = [];
    secs.push({ heading: 'Patient details', lines: [
      p.name + ', ' + p.age + ' years, ' + p.gender + ', blood group ' + p.blood, 'Address: ' + p.address,
      'Allergies: ' + (p.allergies.join(', ') || 'none recorded'),
      'Emergency contacts: ' + p.contacts.map((c) => c.name + ' (' + c.relation + ') ' + c.phone).join('; '),
    ] });
    secs.push({ heading: 'Conditions', lines: p.conditions.map((c) => '* ' + c.name + ' (since ' + c.since + ', ' + c.severity + '): ' + c.notes) });
    secs.push({ heading: 'Current medicines', lines: p.meds.filter((m) => m.active).map((m) =>
      '* ' + m.name + ' ' + m.dose + ' - ' + m.times.map(U.fmtTime12).join(', ') + (m.instructions ? ' (' + m.instructions + ')' : '') + ' | stock ' + m.stock + ' (~' + A.daysLeft(m) + ' days)') });
    const a = A.adherence(p, 7, now);
    const miss = A.analyzeMissed(p, now);
    secs.push({ heading: 'Medicine adherence (last 7 days)', lines: [B(a.pct + '% - ' + a.taken + ' taken, ' + a.missed + ' missed')].concat(miss.length ? miss.map((m) => '* ' + m.text) : ['No repeated missed-dose pattern.']) });
    secs.push({ heading: 'Recent vitals', lines: p.vitals.slice(-6).reverse().map((v) => U.fmtDate(v.date) + ': BP ' + v.sys + '/' + v.dia + ' mmHg, sugar ' + v.sugar + ' mg/dL, pulse ' + v.pulse + ', mood ' + v.mood + ' (by ' + v.by + ')') });
    secs.push({ heading: 'Lab and prescription reports', lines: p.reports.length ? p.reports.flatMap((r) => [B(U.fmtDate(r.date) + ' - ' + r.title + ' [' + r.kind + ', ' + r.flag + ']'), 'By ' + r.by + '. ' + r.summary].concat((r.meds || []).map((m) => '   - ' + m))) : ['No reports on file.'] });
    const notes = p.notes.consult.filter((n) => role !== 'family' || n.shared);
    secs.push({ heading: 'Doctor consultation notes', lines: notes.length ? notes.map((n) => U.fmtDate(n.date) + ' (' + n.by + '): ' + n.text) : ['No notes shared.'] });
    const next = p.appointments.filter((x) => x.status === 'scheduled').sort((x, y) => (x.date + x.time).localeCompare(y.date + y.time));
    secs.push({ heading: 'Upcoming appointments', lines: next.length ? next.map((x) => U.fmtDate(x.date) + ' ' + U.fmtTime12(x.time) + ' - ' + x.title + ' with ' + x.with + ' (' + x.location + ')') : ['None scheduled.'] });
    secs.push({ heading: 'Note', lines: ['Generated by LivedIn from demo data on ' + U.fmtStamp(now) + '. This report supports, but does not replace, professional medical advice.'] });
    return { title: 'LivedIn Patient Report', subtitle: p.name + '  |  ' + U.fmtStamp(now), footer: 'LivedIn - confidential demo report', sections: secs };
  }

  function singleReport(p, r, now) {
    const lines = [B(r.title), 'Type: ' + r.kind + '    Date: ' + U.fmtDate(r.date) + '    Recorded by: ' + r.by + '    Status: ' + r.flag, '', r.summary];
    if (r.meds && r.meds.length) lines.push('', B('Medicines allotted:')), r.meds.forEach((m) => lines.push('* ' + m));
    if (r.file) lines.push('', 'Attached file: ' + r.file.name + ' (' + Math.round(r.file.size / 1024) + ' KB)');
    return { title: 'LivedIn ' + (r.kind === 'lab' ? 'Lab Report' : 'Prescription'), subtitle: p.name + ', ' + p.age + ' y  |  ' + U.fmtStamp(now), footer: 'LivedIn - confidential demo report', sections: [{ heading: r.title, lines }] };
  }

  function adherenceReport(p, now) {
    const a14 = A.adherence(p, 14, now), a7 = A.adherence(p, 7, now);
    const lines = [B('Overall: ' + a7.pct + '% over 7 days, ' + a14.pct + '% over 14 days')];
    for (const m of p.meds.filter((x) => x.active)) { const x = a14.perMed[m.id]; lines.push('* ' + m.name + ' ' + m.dose + ': ' + (x ? x.pct + '% (' + x.taken + ' taken, ' + x.missed + ' missed)' : 'no data')); }
    const miss = A.analyzeMissed(p, now);
    return { title: 'Medication Adherence Report', subtitle: p.name + '  |  ' + U.fmtStamp(now), footer: 'LivedIn - confidential demo report', sections: [
      { heading: 'Adherence summary', lines },
      { heading: 'Daily record (14 days)', lines: a14.perDay.map((d) => U.fmtDate(d.date) + ': ' + d.taken + ' taken, ' + d.missed + ' missed') },
      { heading: 'Patterns', lines: miss.length ? miss.map((m) => '* ' + m.text) : ['No repeated missed doses.'] },
    ] };
  }
  return { patientReport, singleReport, adherenceReport };
});
